/* ================= TEAR-STRIP PEEL MECHANIC ================= */
const unboxingStage = document.getElementById('unboxingStage');
const goodiesDashboard = document.getElementById('goodiesDashboard');
const parcelBox = document.getElementById('parcelBox');
const tearTrack = document.getElementById('tearTrack');
const tearStrip = document.getElementById('tearStrip');
const pullTab = document.getElementById('pullTab');

let isDragging = false;
let startX = 0;
let currentProgress = 0;
let isUnboxed = false;

function completeUnboxing() {
    if (isUnboxed) return;
    isUnboxed = true;

    tearTrack.classList.add('torn');

    tearStrip.style.transition = 'transform 0.4s cubic-bezier(0.25, 1, 0.5, 1), opacity 0.3s ease';
    tearStrip.style.transform = 'scaleX(0)';
    tearStrip.style.opacity = '0';

    setTimeout(() => {
        parcelBox.classList.add('opened');
        if (typeof confetti === 'function') {
            confetti({
                particleCount: 140,
                spread: 95,
                origin: { y: 0.55 },
                colors: ['#ec4899', '#f472b6', '#fde047', '#ffffff', '#db2777']
            });
        }
    }, 250);

    // Transition straight from unboxing to the goodies dashboard
    setTimeout(() => {
        unboxingStage.style.opacity = '0';
        unboxingStage.style.transform = 'scale(0.96)';
        setTimeout(() => {
            unboxingStage.classList.add('hidden');
            goodiesDashboard.classList.add('active');
            window.scrollTo({ top: 0, behavior: 'smooth' });
        }, 500);
    }, 1200);
}

pullTab.addEventListener('pointerdown', (e) => {
    if (isUnboxed) return;
    isDragging = true;
    startX = e.clientX;
    tearStrip.style.transition = 'none';
    pullTab.setPointerCapture(e.pointerId);
});

pullTab.addEventListener('pointermove', (e) => {
    if (!isDragging || isUnboxed) return;
    const trackWidth = tearTrack.offsetWidth;
    const deltaX = Math.max(0, startX - e.clientX);
    currentProgress = Math.min(1, deltaX / (trackWidth * 0.7));
    
    const scaleValue = Math.max(0, 1 - currentProgress);
    tearStrip.style.transform = `scaleX(${scaleValue})`;

    if (currentProgress >= 0.75) {
        isDragging = false;
        completeUnboxing();
    }
});

pullTab.addEventListener('pointerup', (e) => {
    if (!isDragging || isUnboxed) return;
    isDragging = false;
    
    if (currentProgress < 0.2) {
        tearStrip.style.transition = 'transform 0.3s cubic-bezier(0.25, 1, 0.5, 1)';
        tearStrip.style.transform = 'scaleX(1)';
        currentProgress = 0;
    } else {
        completeUnboxing();
    }
});

