/* ================= RENDER CD MIXTAPE PLAYER ================= */
const tracklistEl = document.getElementById('tracklist');
const cdDisc = document.getElementById('cdDisc');
let activeTrackIndex = -1;
let currentAudio = null;

tracksData.forEach((track, idx) => {
    const li = document.createElement('li');
    li.className = 'track-item';
    li.innerHTML = `
        <div>
            <div class="track-title">${track.title}</div>
            <div class="track-note">${track.note}</div>
        </div>
        <span class="play-pill">Play ♪</span>
    `;
    
    li.addEventListener('click', () => {
        document.querySelectorAll('.track-item').forEach(el => {
            el.classList.remove('active');
            el.querySelector('.play-pill').textContent = 'Play ♪';
        });

        if (activeTrackIndex === idx) {
            if (currentAudio) currentAudio.pause();
            activeTrackIndex = -1;
            cdDisc.classList.remove('playing');
        } else {
            if (currentAudio) currentAudio.pause();
            activeTrackIndex = idx;
            li.classList.add('active');
            li.querySelector('.play-pill').textContent = 'Playing...';
            cdDisc.classList.add('playing');

            currentAudio = new Audio(track.file);
            currentAudio.play().catch(err => console.log("Audio play error:", err));
            
            currentAudio.onended = () => {
                cdDisc.classList.remove('playing');
                li.classList.remove('active');
                li.querySelector('.play-pill').textContent = 'Play ♪';
            };
        }
    });
    tracklistEl.appendChild(li);
});